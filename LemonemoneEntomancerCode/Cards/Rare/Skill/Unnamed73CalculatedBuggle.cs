namespace LemonemoneEntomancer.LemonemoneEntomancerCode.Cards.Rare.Skill;

public class Unnamed73CalculatedBuggle() : LemonemoneEntomancerCard(
    2, CardType.Skill, CardRarity.Rare,
    TargetType.Self)
{
    public override BundledHoverTipManager MyBundles =>
    [
        BundledHoverTipFactory.Static(MyEnums.Bugs)
    ];

    protected override async Task OnPlay(
        PlayerChoiceContext choiceContext,
        CardPlay play)
    {
        var cards = await MyActions.DiscardSelection(choiceContext, this, MyEnums.DiscardSelectionType.Any);

        await MyActions.GainBugs(Owner, cards.Count);
    }

    protected override void OnUpgrade()
    {
        AddKeyword(CardKeyword.Retain);
    }
}