namespace LemonemoneEntomancer.LemonemoneEntomancerCode.Cards.Common.Skill;

public class Unnamed20EnfeeblingFlex() : LemonemoneEntomancerCard(2,
    CardType.Skill, CardRarity.Common,
    TargetType.AnyEnemy)
{
    protected override IEnumerable<DynamicVar> CanonicalVars =>
    [
        new PowerVar<Unnamed20EnfeeblingFlexPower>(2),
        new BuzzedVar(12)
    ];

    public override BundledHoverTipManager MyBundles =>
    [
        new BugStrengthBundle()
    ];

    protected override async Task OnPlay(
        PlayerChoiceContext choiceContext,
        CardPlay play)
    {
        await CreatureCmd.TriggerAnim(Owner.Creature, "Cast", Owner.Character.CastAnimDelay);
        
        await CommonActions.ApplySelf<Unnamed20EnfeeblingFlexPower>(choiceContext, this);
        
        await MyActions.Buzzed(choiceContext, play.Target, this);
    }

    protected override void OnUpgrade()
    {
        DynamicVars.Buzzed.UpgradeValueBy(3);
    }
}