namespace LemonemoneEntomancer.LemonemoneEntomancerCode.Cards.Uncommon.Skill;

public class Unnamed42ReBuzzed() : LemonemoneEntomancerCard(0,
    CardType.Skill, CardRarity.Uncommon,
    TargetType.AnyEnemy)
{
    protected override IEnumerable<DynamicVar> CanonicalVars =>
    [
        new PowerVar<Unnamed42ReBuzzedPower>(1),
        new SwarmVar(1)
    ];

    public override IEnumerable<CardKeyword> CanonicalKeywords =>
    [
        MyEnums.Fly,
        CardKeyword.Exhaust
    ];

    public override BundledHoverTipManager MyBundles =>
    [
        new BuzzedBundle()
    ];

    protected override async Task OnPlay(
        PlayerChoiceContext choiceContext,
        CardPlay play)
    {
        await CreatureCmd.TriggerAnim(Owner.Creature, "Cast", Owner.Character.CastAnimDelay);

        await CommonActions.Apply<Unnamed42ReBuzzedPower>(choiceContext, this, play);

        if (IsUpgraded) await MyActions.CreateSwarm(this);
    }
}